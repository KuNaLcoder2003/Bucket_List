create extension if not exists pgcrypto;

create table if not exists public.items (
  id          uuid primary key default gen_random_uuid(),
  gate        int generated by default as identity,
  title       text not null check (char_length(title) between 1 and 120),
  category    text not null default 'fun',
  status      text not null default 'scheduled'
              check (status in ('scheduled', 'boarding', 'delayed', 'departed')),
  rating      int  not null default 0 check (rating between 0 and 5),
  created_by  text not null default 'a' check (created_by in ('a', 'b')),
  created_at  timestamptz not null default now(),
  done_at     timestamptz,
  hearts      jsonb not null default '{}'::jsonb,
  scratched   boolean not null default false
);

create table if not exists public.notes (
  id          uuid primary key default gen_random_uuid(),
  item_id     uuid not null references public.items(id) on delete cascade,
  author      text not null check (author in ('a', 'b')),
  body        text not null check (char_length(body) between 1 and 600),
  created_at  timestamptz not null default now()
);

create table if not exists public.photos (
  id           uuid primary key default gen_random_uuid(),
  item_id      uuid not null references public.items(id) on delete cascade,
  path         text,
  url          text not null,
  uploaded_by  text not null default 'a' check (uploaded_by in ('a', 'b')),
  created_at   timestamptz not null default now()
);

create table if not exists public.settings (
  id      int primary key default 1 check (id = 1),
  name_a  text not null default 'Kunal',
  name_b  text not null default 'Her'
);
insert into public.settings (id) values (1) on conflict (id) do nothing;

-- Access: this app has no login, so anyone with your site link + anon key can
-- read and write. Keep the link between the two of you.
alter table public.items    enable row level security;
alter table public.notes    enable row level security;
alter table public.photos   enable row level security;
alter table public.settings enable row level security;

drop policy if exists "bucket open" on public.items;
drop policy if exists "bucket open" on public.notes;
drop policy if exists "bucket open" on public.photos;
drop policy if exists "bucket open" on public.settings;
create policy "bucket open" on public.items    for all to anon, authenticated using (true) with check (true);
create policy "bucket open" on public.notes    for all to anon, authenticated using (true) with check (true);
create policy "bucket open" on public.photos   for all to anon, authenticated using (true) with check (true);
create policy "bucket open" on public.settings for all to anon, authenticated using (true) with check (true);

-- Live sync between both phones
do $$ begin
  alter publication supabase_realtime add table public.items, public.notes, public.photos, public.settings;
exception when duplicate_object then null; end $$;

-- Photo storage
insert into storage.buckets (id, name, public) values ('photos', 'photos', true)
on conflict (id) do nothing;

drop policy if exists "bucket photos read"   on storage.objects;
drop policy if exists "bucket photos write"  on storage.objects;
drop policy if exists "bucket photos delete" on storage.objects;
create policy "bucket photos read"   on storage.objects for select to anon, authenticated using (bucket_id = 'photos');
create policy "bucket photos write"  on storage.objects for insert to anon, authenticated with check (bucket_id = 'photos');
create policy "bucket photos delete" on storage.objects for delete to anon, authenticated using (bucket_id = 'photos');

